CREATE OR REPLACE TABLE STG_CLAIM_TYPES  AS
WITH VALIDATED_DATA AS (
   SELECT *
   FROM INSURANCE_PROJECT.RAW.CLAIM_TYPES
   WHERE claim_type IS NOT NULL
   AND description IS NOT NULL
),
CLEANED AS (
   SELECT
      upper(claim_type) AS claim_type,
      description
  FROM VALIDATED_DATA
)
SELECT * 
FROM CLEANED