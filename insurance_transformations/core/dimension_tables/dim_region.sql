CREATE OR REPLACE TABLE INSURANCE_PROJECT.CORE.DIM_REGION AS

WITH DEFINED_REGIONS AS (
    SELECT
       INSURANCE_PROJECT.CORE.REGION_KEY_SEQ.NEXTVAL AS region_key,
       region,
       country
    FROM INSURANCE_PROJECT.STAGING.STG_REGIONS
    WHERE LOWER(region) != 'region'
)

SELECT * 
FROM DEFINED_REGIONS;